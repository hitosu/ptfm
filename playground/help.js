    /* a line's runs: titles cyan (the first line, and a line not indented with no ":"), text light
     * grey, keys yellow, readings dark grey, screens in their group's colour, RED red */
    function line(src, title, named) {
        const runs = [];
        const base = title ? D.CYAN : D.LGREY;
        let i = 0, text = "";
        const flush = () => { if (text) runs.push([text, base]); text = ""; };
        while (i < src.length) {
            const ch = src[i];
            if (ch === "{" || ch === "[") {
                const end = src.indexOf(ch === "{" ? "}" : "]", i);
                let name = src.slice(i + 1, end);
                flush();
                i = end + 1;
                if (ch === "[") { runs.push([name, GROUP[name]]); continue; }
                let auto = false;
                if (name.endsWith("*")) { name = name.slice(0, -1); auto = true; }
                runs.push([name, D.YELLOW]);
                const r = READ[name];
                if (auto && r && !named.has(name)) { runs.push([" (" + r + ")", D.DGREY]); named.add(name); continue; }
                if (r && src.startsWith(" (" + r + ")", i)) {
                    runs.push([" (" + r + ")", D.DGREY]);
                    named.add(name);
                    i += r.length + 3;
                }
                continue;
            }
            if (src.startsWith("RED", i) && !/[A-Z]/.test(src[i + 3] || "") && !/[A-Z]/.test(src[i - 1] || "")) {
                flush();
                runs.push(["RED", D.RED]);
                i += 3;
                continue;
            }
            text += ch;
            i++;
        }
        flush();
        return runs;
    }
    const isTitle = (s, first) => first || (s && s[0] !== " " && !s.replace(/\{[^}]*\}|\[[^\]]*\]/g, "").includes(":"));

    function pages(screen) {
        const own = OWN[screen] || [], list = screen === "STATUS" ? SHARED.concat(own) : own.concat(SHARED);
        const named = new Set();
        return list.map((pg, k) => {
            const lines = pg.map((s, j) => line(s, isTitle(s, j === 0), named));
            if (k === 0) {
                while (lines.length < 16) lines.push([]);
                lines.push([["PRESS ", D.LGREY], ["HOME", D.YELLOW], [" TO GET BACK", D.LGREY]]);
            }
            return lines;
        });
    }
    /* the help's own check (specs/ui/help.md): 40 characters, 17 lines, the fonts' characters */
    function check() {
        const bad = [];
        for (const s in OWN) {                           /* a first page: 15 lines of its own, a blank, PRESS HOME */
            const first = (s === "STATUS" ? SHARED.concat(OWN[s]) : OWN[s].concat(SHARED))[0];
            if (first.length > 15) bad.push(`${s} page 1: ${first.length} lines of its own (15 at most)`);
        }
        for (const s in OWN) pages(s).forEach((pg, k) => {
            if (pg.length > 17) bad.push(`${s} page ${k + 1}: ${pg.length} lines`);
            for (const ln of pg) {
                const t = ln.map(r => r[0]).join("");
                if (t.length > 40) bad.push(`${s} page ${k + 1}: ${t.length} characters: ${t}`);
                if (/[^\x20-\x60{|}~]/.test(t)) bad.push(`${s} page ${k + 1}: a character the fonts lack: ${t}`);  /* printable ASCII but lowercase */
            }
        });
        return bad;
    }
    return { pages, check, READ, GROUP, source: () => ({ own: OWN, shared: SHARED }) };
