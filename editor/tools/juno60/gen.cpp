// The Juno-60 conversion's generator: editor/js/juno60_tables.js (the tables and the arrays the page's rules read)
// and vectors.json beside this file (patches made up here, every field at its ends and between, with what the
// conversion makes of them: the page's tests compare editor/js/juno60.js with them). run.sh builds and runs it.
//
//   gen TABLES.js VECTORS.json
#include "convert.h"
#include <cstdio>
#include <string>

static void arr(FILE *f, const char *name, const uint8_t *a, int n)
{
    fprintf(f, "    %s: [", name);
    for (int i = 0; i < n; i++) fprintf(f, "%s%d", i ? (i % 32 ? "," : ",\n        ") : "", a[i]);
    fprintf(f, "],\n");
}
template <typename T> static void arri(FILE *f, const char *name, const T *a, int n, int per = 16)
{
    fprintf(f, "    %s: [", name);
    for (int i = 0; i < n; i++) fprintf(f, "%s%lld", i ? (i % per ? "," : ",\n        ") : "", (long long)a[i]);
    fprintf(f, "],\n");
}
static void arrd(FILE *f, const char *name, const double *a, int n)
{
    fprintf(f, "    %s: [", name);
    for (int i = 0; i < n; i++) fprintf(f, "%s%.9f", i ? (i % 8 ? "," : ",\n        ") : "", a[i]);
    fprintf(f, "],\n");
}

int main(int argc, char **argv)
{
    if (argc != 3) { fprintf(stderr, "usage: gen TABLES.js VECTORS.json\n"); return 2; }
    static c60::Tab t;
    c60::buildTab(t);
    FILE *f = fopen(argv[1], "w");
    if (!f) { perror(argv[1]); return 1; }
    fprintf(f,
        "/* SPDX-License-Identifier: GPL-3.0-only\n"
        " * Copyright (C) 2026 Vasily Kazantsev */\n"
        "/* Generated by editor/tools/juno60/ (run.sh) from Ultramaster KR-106's (GPL-3.0) models of the Juno-60 and the\n"
        " * Juno-106 and from PT/FM's own Juno-106 engine (fw/core/eng/juno): the Juno-60 conversion's tables and the arrays\n"
        " * its rules read (editor/js/juno60.js; specs/editor.md, Juno-60 patches as Juno-106 ones). Kept as generated.\n"
        " *   the tables: a Juno-60 tape value (0-255) -> the Juno-106 byte whose quantity on PT/FM's engine comes closest\n"
        " *   (ENV A and ENV S: one table for VCA MODE ENV, as heard through each VCA, one for GATE)\n"
        " *   HZ106: log2 of the cutoff in Hz x 10000 at each 12-bit cutoff code (the 14-bit code >> 2); HZ60: the Juno-60's\n"
        " *   at each VCF FREQ; ENV60P / ENV60N: the Juno-60's VCF ENV in octaves x 10000 at the envelope's peak (+, -);\n"
        " *   VLFO60: its VCF LFO at the LFO's peak; KBD60: its VCF KYBD over two octaves; CAP, FLOOR: 0.85 x Nyquist and\n"
        " *   20 Hz; R60TAU: its release's time constant (us); from each of 33 envelope levels (j / 32, 0 as 1 / 64) its\n"
        " *   release's time to a tenth of the level (RRAT60) and its sound's, through its VCA, to fall 20 dB (RSND60), in\n"
        " *   time constants x 10000, and PT/FM's times for the same (R106ENV, RSND106: 0.1 ms, 128 bytes a level); ACOEF /\n"
        " *   DCOEF: the Juno-60's attack and decay as steps of 1 ms; Q15: PT/FM's pulse width per DCO PWM byte */\n"
        "(function (ED) {\n\"use strict\";\nED.juno60tab = {\n");
    fprintf(f, "    HPF_122: %d,\n", c60::HPF_122);
    arr(f, "ENV_A_ENV", t.ENV_A_ENV, 256); arr(f, "ENV_A_GATE", t.ENV_A_GATE, 256); arr(f, "ENV_D", t.ENV_D, 256); arr(f, "VCF_FREQ", t.VCF_FREQ, 256);
    arr(f, "VCF_RES", t.VCF_RES, 256); arr(f, "LFO_RATE", t.LFO_RATE, 256); arr(f, "LFO_DELAY", t.LFO_DELAY, 256);
    arr(f, "DCO_LFO", t.DCO_LFO, 256); arr(f, "DCO_PWM", t.DCO_PWM, 256); arr(f, "DCO_SUB", t.DCO_SUB, 256);
    arr(f, "DCO_NOISE", t.DCO_NOISE, 256); arr(f, "VCA_LEVEL", t.VCA_LEVEL, 256); arr(f, "ENV_S_ENV", t.ENV_S_ENV, 256);
    arr(f, "ENV_S_GATE", t.ENV_S_GATE, 256);
    arri(f, "HZ60", t.HZ60, 256); arri(f, "ENV60P", t.ENV60P, 256); arri(f, "ENV60N", t.ENV60N, 256);
    arri(f, "VLFO60", t.VLFO60, 256); arri(f, "KBD60", t.KBD60, 256);
    fprintf(f, "    CAP: %d,\n    FLOOR: %d,\n", t.CAP, t.FLOOR);
    arri(f, "R60TAU", t.R60TAU, 256, 12); arri(f, "RRAT60", t.RRAT60, 33); arri(f, "RSND60", t.RSND60, 33);
    arri(f, "R106ENV", t.R106ENV, 33 * 128, 12); arri(f, "RSND106", t.RSND106, 33 * 128, 12);
    arrd(f, "ACOEF", t.ACOEF, 256); arrd(f, "DCOEF", t.DCOEF, 256);
    arri(f, "Q15", t.Q15, 106);
    arri(f, "HZ106", t.HZ106, 4096, 16);
    fprintf(f, "};\n})(globalThis.ED = globalThis.ED || {});\n");
    fclose(f);

    /* the vectors: every slider at its ends and between, the switches in every combination, then patches at random */
    FILE *g = fopen(argv[2], "w");
    if (!g) { perror(argv[2]); return 1; }
    fprintf(g, "[\n");
    uint32_t seed = 12345;
    auto rnd = [&](int n) { seed = seed * 1103515245u + 12345u; return (int)((seed >> 16) % (uint32_t)n); };
    static const int EDGE[] = {0, 1, 18, 28, 29, 64, 127, 128, 200, 253, 254, 255};
    const int N = 400;
    for (int i = 0; i < N; i++) {
        int s[16];
        for (int k = 0; k < 16; k++) s[k] = i < 96 ? EDGE[(i + 5 * k) % 12] : rnd(256);
        int sw = i < 96 ? i : rnd(1 << 11);
        c60::Patch60 v{s[0], s[1], s[2], s[3], s[4], s[5], s[6], s[7], s[8], s[9], s[10], s[11], s[12], s[13], s[14], s[15],
                       sw & 1, (sw >> 1) % 3, (sw >> 3) & 3, (sw >> 5) & 1, (sw >> 6) & 1, (sw >> 7) & 1, (sw >> 8) & 1,
                       (sw >> 9) & 1, (sw >> 10) & 1, (sw >> 4) & 1, (sw >> 2) & 1};
        if (i % 7 == 3) { v.pwm_source = 2; v.pulse = 1; }   /* (PWM by ENV that matters: often) */
        c60::Result r = c60::convert(t, v);
        fprintf(g, "{\"v\":{\"vcf_env\":%d,\"vcf_lfo\":%d,\"vcf_kybd\":%d,\"vca_level\":%d,\"env_a\":%d,\"env_r\":%d,\"env_d\":%d,"
                   "\"env_s\":%d,\"vcf_freq\":%d,\"dco_noise\":%d,\"dco_sub\":%d,\"vcf_res\":%d,\"dco_pwm\":%d,\"lfo_rate\":%d,"
                   "\"dco_lfo\":%d,\"lfo_delay\":%d,\"env_polarity\":%d,\"pwm_source\":%d,\"hpf\":%d,\"vca_gate\":%d,"
                   "\"lfo_trigger\":%d,\"chorus1\":%d,\"pulse\":%d,\"saw\":%d,\"sub_on\":%d,\"chorus2\":%d,\"chorus_off\":%d},"
                   "\"p\":[",
                v.vcf_env, v.vcf_lfo, v.vcf_kybd, v.vca_level, v.env_a, v.env_r, v.env_d, v.env_s, v.vcf_freq, v.dco_noise,
                v.dco_sub, v.vcf_res, v.dco_pwm, v.lfo_rate, v.dco_lfo, v.lfo_delay, v.env_polarity, v.pwm_source, v.hpf,
                v.vca_gate, v.lfo_trigger, v.chorus1, v.pulse, v.saw, v.sub_on, v.chorus2, v.chorus_off);
        for (int k = 0; k < 18; k++) fprintf(g, "%s%d", k ? "," : "", r.p[k]);
        fprintf(g, "],\"pwmEnv\":%s}%s\n", r.pwmEnv ? "true" : "false", i + 1 < N ? "," : "");
    }
    fprintf(g, "]\n");
    fclose(g);
    return 0;
}
