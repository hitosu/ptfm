"""fw/tests/vectors.json (MIDI CONTROLLER's protocol table, shared with the page's test, tests/controller_page.js)
as a C header for ctl_test.c.

  fw/tests/gen_vectors.py OUT.h
"""
import json
import sys
from pathlib import Path

V = json.loads((Path(__file__).resolve().parent / "vectors.json").read_text(encoding="utf-8"))
KIND = {"key": 0, "button": 1, "knob": 2, "master": 3}
STATE = {"off": 0, "dim": 1, "lit": 2}


def arr(b):
    return "{" + ", ".join(str(x) for x in b) + "}"


A = V["handshake"]["answer"]
out = ["/* generated by fw/tests/gen_vectors.py from fw/tests/vectors.json: do not edit */",
       "typedef struct { int kind, id, val; uint8_t midi[3]; } vec_out_t;   /* val: down, clicks or MASTER */",
       "typedef struct { uint8_t midi[3]; int led, state; } vec_led_t;",
       f"static const uint8_t VEC_ASK[] = {arr(V['handshake']['ask'])};",
       f"static const uint8_t VEC_ANSWER[3][10] = {{{arr(A['mirror'])}, {arr(A['general'])}, "
       f"{arr(A['mirror_channel_5'])}}};   /* mirror, general, mirror on channel 5 */"]


def outs(name, items):
    out.append(f"static const vec_out_t {name}[] = {{")
    for v in items:
        e = v["event"]
        kind = next(k for k in KIND if k in e)
        val = int(e["down"]) if "down" in e else e.get("clicks", e.get("master"))
        out.append(f"    {{{KIND[kind]}, {e[kind] if kind != 'master' else 0}, {val}, {arr(v['midi'])}}},")
    out.append("};")


def leds(name, items):
    out.append(f"static const vec_led_t {name}[] = {{")
    for v in items:
        out.append(f"    {{{arr(v['midi'])}, {v['fm1']['led']}, {STATE[v['fm1']['state']]}}},")
    out.append("};")


outs("VEC_OUT", V["mirror_out"])
leds("VEC_LED", V["mirror_leds"] + V["mirror_led_levels"])
outs("VEC_OUT5", [v for v in V["mirror_channel_5"] if "event" in v])
leds("VEC_LED5", [v for v in V["mirror_channel_5"] if "fm1" in v])
Path(sys.argv[1]).write_text("\n".join(out) + "\n", encoding="utf-8")
