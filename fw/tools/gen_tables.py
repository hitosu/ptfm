"""The sound's tables (fw/core/eng/, play/, fx/), computed here: the FM-1 has no FPU.

    python3 -I fw/tools/gen_tables.py GEN      (fw/tools/gen.py runs it)

  GEN/dx7_tables.h     MSFA's tables (fw/tools/gen_dx7.py)
  GEN/chip_tables.h    the CHIP engine's tables (fw/tools/gen_chip.py)
  GEN/sound_tables.h   LEVEL_Q16[256]: an instrument's LEVEL (signed half-dB, index LEVEL + 128) as a gain,
                       Q16; the effects' tables (fx.c)
  GEN/juno_rel_tables.h  the Juno-106's ticks to silence after a let-go, by RELEASE (juno_release_ticks, juno.c),
                       from fw/core/eng/juno/juno_tables.h's JUNO_DECREL and JUNO_VCA
"""
import importlib.util
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True           # (no __pycache__ in the tree)


def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def arr(name, ctype, vals, per=12):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def juno_array(text, name, n):
    """juno_tables.h's array `name` (n values)"""
    m = re.search(r"\b%s\[%d\] = \{([^}]*)\}" % (name, n), text)
    vals = [int(v) for v in m.group(1).split(",") if v.strip()] if m else []
    if len(vals) != n:
        raise SystemExit("gen_tables: %s[%d] not found in juno_tables.h" % (name, n))
    return vals


def juno_rel_lines():
    """the ticks from a let-go at the envelope's top (0x3FFF) until the envelope is under JUNO_REL_SILENT, the lowest
    envelope whose VCA gain (vca_target's curve, before the levels) is 1 or more, by RELEASE: calc_decay's arithmetic
    (KR106ADSR CalcDecay) on JUNO_DECREL's coefficient a tick, as env_tick's RELEASE runs it"""
    with open(os.path.join(HERE, "..", "core", "eng", "juno", "juno_tables.h")) as f:
        text = f.read()
    decrel, vca = juno_array(text, "JUNO_DECREL", 128), juno_array(text, "JUNO_VCA", 257)

    def gain(env):                       # vca_target's curve (juno.c vca_gain)
        x = (env * 1020) >> 8
        i, fr = x >> 8, x & 255
        return vca[i] + (((vca[i + 1] - vca[i]) * fr) >> 8)

    def decay(v, c):                     # calc_decay
        vh, vl, ch, cl = v >> 8, v & 255, c >> 8, c & 255
        return (vh * ch + ((vh * cl) >> 8) + ((vl * ch) >> 8)) & 0xFFFF

    silent = next(e for e in range(0x4000) if gain(e) >= 1)
    ticks = []
    for c in decrel:
        v, n = 0x3FFF, 0
        while v >= silent:
            v, n = decay(v, c), n + 1
        ticks.append(n)
    out = ["/* generated by fw/tools/gen_tables.py from fw/core/eng/juno/juno_tables.h: juno_release_ticks' table */",
           "#ifndef JUNO_REL_TABLES_H", "#define JUNO_REL_TABLES_H", "#include <stdint.h>",
           "/* the lowest envelope whose VCA gain (the curve, before the levels) is 1 or more: under it the VCA's target",
           " * is 0 at any level */",
           "#define JUNO_REL_SILENT %d" % silent,
           "/* the ticks from a let-go at the envelope's top (0x3FFF) until it is under JUNO_REL_SILENT, by RELEASE */"]
    out += arr("JUNO_REL_TICKS", "uint16_t", ticks, 16)
    out += ["#endif"]
    return out


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    gen = sys.argv[1]
    os.makedirs(gen, exist_ok=True)
    dx7 = load("gen_dx7")
    argv, sys.argv = sys.argv, ["gen_dx7.py", os.path.join(gen, "dx7_tables.h")]
    try:
        dx7.main()
    finally:
        sys.argv = argv
    chip = load("gen_chip")                                     # GEN/chip_tables.h (the CHIP engine's)
    with open(os.path.join(gen, "chip_tables.h"), "w") as f:
        f.write(chip.c_text(chip.data()))
    fx = load("gen_fx")
    out = ["/* generated by fw/tools/gen_tables.py */",
           "#ifndef SOUND_TABLES_H", "#define SOUND_TABLES_H", "#include <stdint.h>",
           "#ifndef PLAT_C2_RO", "#define PLAT_C2_RO                       /* (core 2's constant tables: plat.h) */",
           "#endif",
           "/* an instrument's LEVEL (signed, half-dB) as a gain, Q16: LEVEL_Q16[LEVEL + 128] */"]
    out += arr("LEVEL_Q16", "uint32_t", [round(65536 * 10 ** ((v - 128) / 40)) for v in range(256)], 8)
    out += fx.c_lines()
    out += ["#endif"]
    with open(os.path.join(gen, "sound_tables.h"), "w") as f:
        f.write("\n".join(out) + "\n")
    with open(os.path.join(gen, "juno_rel_tables.h"), "w") as f:   # (juno.c's juno_release_ticks)
        f.write("\n".join(juno_rel_lines()) + "\n")


if __name__ == "__main__":
    main()
