"""The sound's tables (fw/core/eng/, play/, fx/), computed here: the FM-1 has no FPU.

    python3 -I fw/tools/gen_tables.py GEN      (fw/tools/gen.py runs it)

  GEN/dx7_tables.h     MSFA's tables (fw/tools/gen_dx7.py)
  GEN/chip_tables.h    the CHIP engine's tables (fw/tools/gen_chip.py)
  GEN/sound_tables.h   LEVEL_Q16[256]: an instrument's LEVEL (signed half-dB, index LEVEL + 128) as a gain,
                       Q16; the effects' tables (fx.c)
"""
import importlib.util
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True           # (no __pycache__ in the tree)


def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + ".py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def arr(name, ctype, vals, per=12):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    gen = sys.argv[1]
    os.makedirs(gen, exist_ok=True)
    dx7 = load("gen_dx7")
    argv, sys.argv = sys.argv, ["gen_dx7.py", os.path.join(gen, "dx7_tables.h")]
    try:
        dx7.main()
    finally:
        sys.argv = argv
    chip = load("gen_chip")                                     # GEN/chip_tables.h (the CHIP engine's)
    with open(os.path.join(gen, "chip_tables.h"), "w") as f:
        f.write(chip.c_text(chip.data()))
    fx = load("gen_fx")
    out = ["/* generated by fw/tools/gen_tables.py */",
           "#ifndef SOUND_TABLES_H", "#define SOUND_TABLES_H", "#include <stdint.h>",
           "#ifndef PLAT_C2_RO", "#define PLAT_C2_RO                       /* (core 2's constant tables: plat.h) */",
           "#endif",
           "/* an instrument's LEVEL (signed, half-dB) as a gain, Q16: LEVEL_Q16[LEVEL + 128] */"]
    out += arr("LEVEL_Q16", "uint32_t", [round(65536 * 10 ** ((v - 128) / 40)) for v in range(256)], 8)
    out += fx.c_lines()
    out += ["#endif"]
    with open(os.path.join(gen, "sound_tables.h"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
