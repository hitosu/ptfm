"""USB audio's resampler table (specs/connections.md#usb-audio): a polyphase windowed sinc, Q15, written to
fw/device/uac_fir.h (kept in the tree: the device's sources do not see the generated ones).

    python3 -I fw/tools/gen_uac.py            write it
    python3 -I fw/tools/gen_uac.py --check    0 when the file is what this makes (fw/tests/run_uac.sh)

UAC_FIR[p][j]: the output at mu = p / UAC_FIR_P past input frame i takes input frames i - N/2 + 1 .. i + N/2,
tap j the frame i - N/2 + 1 + j; mu between two phases takes their taps interpolated (row P is mu = 1, so the
last phase has a neighbour). The sinc cuts at FC of the FM-1's rate (both the computer's rates are at least
it: 44.1 and 48 kHz), Kaiser-windowed (BETA); each phase's taps sum to 32768 exactly, so a constant passes
unchanged whatever the phase.
"""
import math
import os
import sys

N = 16                                   # taps a phase
P = 128                                  # phases (the fraction's top 7 bits)
FC = 0.43                                # the cut, of the input's rate (~19 kHz)
BETA = 7.0                               # the Kaiser window's (about -70 dB side lobes)
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "device", "uac_fir.h")


def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2
        s += t
        k += 1
    return s


def table():
    rows = []
    half = N / 2
    for p in range(P + 1):                               # (row P: mu = 1, for the last phase's interpolation)
        mu = p / P
        h = []
        for j in range(N):
            d = j - (half - 1) - mu                      # the tap's distance from the output, in input frames
            x = 2 * FC * d
            s = 2 * FC * (1.0 if abs(x) < 1e-12 else math.sin(math.pi * x) / (math.pi * x))
            w = d / half                                 # the window over (-N/2, N/2)
            win = i0(BETA * math.sqrt(max(0.0, 1 - w * w))) / i0(BETA) if abs(w) < 1 else 0.0
            h.append(s * win)
        sm = sum(h)
        q = [round(32768 * v / sm) for v in h]
        q[max(range(N), key=lambda j: abs(q[j]))] += 32768 - sum(q)     # (exactly unity)
        rows.append(q)
    return rows


def text():
    out = ["/* generated by fw/tools/gen_uac.py: USB audio's resampler, a polyphase windowed sinc (Q15), each phase's",
           " * taps summing to 32768 */",
           "#ifndef UAC_FIR_H", "#define UAC_FIR_H", "#include <stdint.h>",
           "#define UAC_FIR_N %d                     /* taps a phase */" % N,
           "#define UAC_FIR_P %d                    /* phases */" % P,
           "#ifndef UAC_FIR_MEM",
           "#define UAC_FIR_MEM const               /* (fw/device/uac.h: none, the table in RAM) */",
           "#endif",
           "static UAC_FIR_MEM int16_t UAC_FIR[UAC_FIR_P + 1][UAC_FIR_N] = {   /* (row P: mu = 1, interpolating) */"]
    for r in table():
        out.append("    {" + ", ".join(str(v) for v in r) + "},")
    out += ["};", "#endif"]
    return "\n".join(out) + "\n"


def main():
    t = text()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT) as f:
                same = f.read() == t
        except OSError:
            same = False
        print("uac_fir.h: as made" if same else "uac_fir.h: NOT what fw/tools/gen_uac.py makes")
        sys.exit(0 if same else 1)
    with open(OUT, "w") as f:
        f.write(t)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
